import { EventDetails, BudgetItem, TimelineItem, Guest, SeatingTable, ChecklistItem } from '../types';

export interface FullEventExportData {
  version: string;
  exportedAt: string;
  event: EventDetails;
  budgetItems: BudgetItem[];
  timelineItems: TimelineItem[];
  checklistItems: ChecklistItem[];
  tables: SeatingTable[];
  guests: Guest[];
}

export function exportEventToJSON(data: FullEventExportData): void {
  const jsonString = `data:text/json;charset=utf-8,${encodeURIComponent(
    JSON.stringify(data, null, 2)
  )}`;
  const downloadAnchor = document.createElement('a');
  downloadAnchor.setAttribute('href', jsonString);
  const safeFilename = `${data.event.title.toLowerCase().replace(/[^a-z0-9]/g, '-')}-blueprint.json`;
  downloadAnchor.setAttribute('download', safeFilename);
  document.body.appendChild(downloadAnchor);
  downloadAnchor.click();
  downloadAnchor.remove();
}

export function parseImportedJSON(jsonText: string): FullEventExportData {
  const parsed = JSON.parse(jsonText);
  if (!parsed.event || !parsed.event.title) {
    throw new Error('Invalid event configuration file format.');
  }
  return parsed as FullEventExportData;
}

export function generateRunOfShowMarkdown(
  event: EventDetails,
  timelineItems: TimelineItem[],
  budgetItems: BudgetItem[]
): string {
  const totalSpent = budgetItems.reduce((acc, i) => acc + (i.actualAmount || i.allocatedAmount || 0), 0);

  let md = `# ${event.title.toUpperCase()} — MASTER RUN OF SHOW\n`;
  md += `**Vertical:** ${event.vertical} | **Vibe:** ${event.vibe}\n`;
  md += `**Date:** ${event.date} | **Hours:** ${event.startTime} - ${event.endTime}\n`;
  md += `**Venue:** ${event.location} (${event.isOutdoor ? 'Outdoor' : 'Indoor'})\n`;
  md += `**Guest Target:** ${event.targetGuestCount} | **Budget Total:** $${event.totalBudget.toLocaleString()} ($${totalSpent.toLocaleString()} committed)\n\n`;

  md += `## 🕒 DAY-OF TIMELINE & CUE SHEET\n`;
  md += `| Time | Milestone | Lead / Dept | Location | Description |\n`;
  md += `| :--- | :--- | :--- | :--- | :--- |\n`;

  const sortedTimeline = [...timelineItems].sort((a, b) => a.time.localeCompare(b.time));
  sortedTimeline.forEach(item => {
    md += `| **${item.time}** | ${item.title} | ${item.leadPersonnel} | ${item.location || 'Main Venue'} | ${item.description.replace(/\n/g, ' ')} |\n`;
  });

  md += `\n---\n*Generated by CelebAura AI — Autonomous Event Planner*`;
  return md;
}

